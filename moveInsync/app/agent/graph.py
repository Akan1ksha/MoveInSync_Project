def clarify_node(state: GraphState) -> GraphState:
    """
    Emits a clarifying question to the user and halts this turn.
    No LLM call — the question is generated by parse_intent_node.
    """
    # reply already set by parse_intent_node
    state["next_action"] = "done"
    return state


def check_roster_node(state: GraphState) -> GraphState:
    """Calls get_employee_roster tool. No LLM call."""
    result = get_employee_roster(state["company_id"], state["employee_id"])
    if "error" in result:
        state["reply"] = result["error"]
        state["next_action"] = "done"
        return state

    entries = result.get("entries", [])
    if not entries:
        state["reply"] = "I couldn't find any roster entries for today. Please contact the transport desk."
        state["next_action"] = "done"
        return state

    # TODO: match to requested trip type and store roster_entry_id
    state["roster_entry_id"] = entries[0].get("id")
    state["next_action"] = "check_policy"
    return state


def check_policy_node(state: GraphState) -> GraphState:
    """Enforces cut-off rules. No LLM call."""
    if not state.get("requested_time"):
        state["reply"] = "Please tell me what time you'd like to change to."
        state["next_action"] = "done"
        return state

    result = check_policy(
        state["company_id"],
        state.get("intent", "").replace("change_", ""),
        state["requested_time"],
    )

    if "error" in result:
        state["reply"] = result["error"]
        state["next_action"] = "done"
        return state

    if not result["allowed"]:
        if result.get("requires_manager_approval"):
            state["reply"] = (
                f"This change is outside the allowed window. {result['reason']} "
                "Would you like me to escalate this to your transport manager?"
            )
            state["next_action"] = "escalate"
        else:
            state["reply"] = result["reason"]
            state["next_action"] = "done"
        return state

    state["next_action"] = "find_cab"
    return state


def find_cab_node(state: GraphState) -> GraphState:
    """Calls get_cab_options tool. No LLM call."""
    trip_type = state.get("intent", "").replace("change_", "")
    result = get_cab_options(state["company_id"], trip_type, state["requested_time"])

    if "error" in result:
        state["reply"] = result["error"]
        state["next_action"] = "done"
        return state

    options = result.get("options", [])
    if not options:
        state["reply"] = (
            f"There are no available cabs around {state['requested_time']} for your company. "
            "The transport desk has been notified."
        )
        state["next_action"] = "done"
        return state

    best = options[0]
    state["chosen_cab_id"] = best["cab_id"]
    # LLM call #2: format a natural-language offer to the user
    # TODO: replace stub with real call_llm()
    state["reply"] = (
        f"I found a cab at {best['time']} on route {best['route']} with "
        f"{best['seats_available']} seat(s) free. Shall I confirm this change?"
    )
    state["next_action"] = "await_confirm"
    state["llm_calls"] = state.get("llm_calls", 0) + 1
    return state


def escalate_node(state: GraphState) -> GraphState:
    """Raises a manager escalation and suspends the conversation."""
    request_id = state.get("request_id") or str(uuid.uuid4())
    state["request_id"] = request_id

    result = raise_manager_escalation(
        state["company_id"],
        state["employee_id"],
        request_id,
        reason="Outside cut-off window",
    )
    state["reply"] = result["message"]
    state["pending_manager"] = True
    state["next_action"] = "done"
    return state


def apply_change_node(state: GraphState) -> GraphState:
    """Applies the confirmed change. No LLM call."""
    if not state.get("chosen_cab_id") or not state.get("request_id"):
        state["reply"] = "Something went wrong — I lost track of the cab details. Please start over."
        state["next_action"] = "done"
        return state

    result = apply_shift_change(
        state["company_id"],
        state["employee_id"],
        state["roster_entry_id"],
        state["chosen_cab_id"],
        state["requested_time"],
        state["request_id"],
    )

    if result.get("success"):
        state["reply"] = result["confirmation"]
    else:
        state["reply"] = result.get("error", "The change could not be applied. Please try again.")

    state["next_action"] = "done"
    return state


def resume_node(state: GraphState) -> GraphState:
    """
    Re-entered after manager decision arrives.
    Decides next step based on decision (approved → apply, rejected → inform).
    """
    decision = state.get("manager_decision")
    if decision == "approved":
        state["next_action"] = "apply"
    else:
        state["reply"] = (
            "Your transport manager has declined this change. "
            "Your original trip remains as scheduled."
        )
        state["next_action"] = "done"
    return state


# ---------------------------------------------------------------------------
# Router
# ---------------------------------------------------------------------------

def route(state: GraphState) -> str:
    """Edge function — returns the name of the next node."""
    return state.get("next_action", "done")


# ---------------------------------------------------------------------------
# Graph assembly
# ---------------------------------------------------------------------------

def build_graph() -> StateGraph:
    g = StateGraph(GraphState)

    g.add_node("parse_intent", parse_intent_node)
    g.add_node("clarify", clarify_node)
    g.add_node("check_roster", check_roster_node)
    g.add_node("check_policy", check_policy_node)
    g.add_node("find_cab", find_cab_node)
    g.add_node("escalate", escalate_node)
    g.add_node("apply_change", apply_change_node)
    g.add_node("resume", resume_node)

    g.set_entry_point("parse_intent")

    g.add_conditional_edges(
        "parse_intent",
        route,
        {
            "clarify": "clarify",
            "check_roster": "check_roster",
            "done": END,
        },
    )
    g.add_conditional_edges(
        "check_roster",
        route,
        {"check_policy": "check_policy", "done": END},
    )
    g.add_conditional_edges(
        "check_policy",
        route,
        {"find_cab": "find_cab", "escalate": "escalate", "done": END},
    )
    g.add_conditional_edges(
        "find_cab",
        route,
        {"await_confirm": END, "done": END},
    )
    g.add_conditional_edges(
        "resume",
        route,
        {"apply": "apply_change", "done": END},
    )

    g.add_edge("clarify", END)
    g.add_edge("escalate", END)
    g.add_edge("apply_change", END)

    return g.compile()


GRAPH = build_graph()
