"""
LangGraph agent graph definition.

Design decisions
----------------
* State lives in GraphState (TypedDict). Serialising it to JSON and saving
  to ConversationState table lets us resume after a process restart without
  needing a full LangGraph checkpoint backend.

* LLM call budget: at most MAX_LLM_CALLS_PER_TURN (4) per employee message.
  Enforced by incrementing `llm_calls` in state and refusing to call the LLM
  again once the ceiling is hit.

* All tool calls go through Python functions, never raw LLM output.
  The model DECIDES which tool to call and with what arguments;
  Python VALIDATES the company_id from the JWT before executing.

* The "pending_manager" node parks the conversation. A separate API endpoint
  (POST /requests/{id}/decision) writes the decision to DB and calls
  resume_paused_conversation(), which re-enters the graph at "resume_node".

* Clarification: if the LLM returns a ClarifyAction, the graph emits the
  question and waits for the next user message (no tool is called).
"""
from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from typing import Annotated, Any, Optional, TypedDict

from langgraph.graph import StateGraph, END

from app.core.config import get_settings
from app.tools.roster_tools import (
    get_employee_roster,
    get_cab_options,
    check_policy,
    apply_shift_change,
    raise_manager_escalation,
)
from app.llm.client import call_llm, LLMBudgetExceeded

settings = get_settings()


# ---------------------------------------------------------------------------
# State schema
# ---------------------------------------------------------------------------

class GraphState(TypedDict):
    # Identity — set once from JWT, never touched by the model
    company_id: str
    employee_id: str
    conversation_id: str

    # Conversation history sent to the LLM (trimmed to last N turns)
    messages: list[dict]        # [{"role": "user"|"assistant"|"tool", "content": str}]

    # Agent working memory
    intent: Optional[str]       # "change_pickup" | "change_drop" | "cancel" | "query"
    requested_time: Optional[str]
    roster_entry_id: Optional[str]
    chosen_cab_id: Optional[str]
    request_id: Optional[str]

    # Flow control
    llm_calls: int              # incremented every LLM call
    next_action: str            # drives routing: "tool" | "clarify" | "escalate" | "apply" | "done"
    pending_manager: bool
    manager_decision: Optional[str]

    # What to tell the user
    reply: str


# ---------------------------------------------------------------------------
# Nodes
# ---------------------------------------------------------------------------

